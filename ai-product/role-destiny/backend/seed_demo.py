BASE = "http://127.0.0.1:8000/api"
REPORT = []

s = requests.Session()


def log(msg):
    REPORT.append(msg)
    print(msg)


def login():
    r = s.post(BASE + "/admin/login",
               json={"username": "admin", "password": "gongge@2026"}).json()
    s.headers["Authorization"] = "Bearer " + r["token"]


def existing_tests():
    return s.get(BASE + "/admin/tests").json()


def create_theme(title, desc, share_title, share_desc, sort_order, price=99):
    r = s.post(BASE + "/admin/tests", json={
        "title": title, "description": desc,
        "share_title": share_title, "share_desc": share_desc,
        "price": price, "status": 1, "sort_order": sort_order,
    }).json()
    log("[+] 主题创建成功: %s (id=%s)" % (title, r["id"]))
    return r["id"]


def add_role(tid, r):
    body = {
        "test_id": tid, "name": r["name"], "code": r["code"],
        "description": r["desc"], "rarity": r["rarity"],
        "detail_text": r.get("detail", ""), "personality": r.get("personality", ""),
        "destiny": r.get("destiny", ""), "advantages": r.get("adv", []),
        "weaknesses": r.get("weak", []), "suggestion": r.get("sugg", ""),
        "lucky_number": r.get("lnum", ""), "lucky_color": r.get("lcolor", ""),
        "motto": r.get("motto", ""), "sort_order": r["sort"],
    }
    resp = s.post(BASE + "/admin/roles", json=body)
    if resp.status_code != 200:
        raise RuntimeError("角色创建失败 %s: %s" % (r["name"], resp.text))


def add_question(tid, content, options, sort_order):
    body = {"content": content, "sort_order": sort_order,
            "options": [{"content": c, "score_map": m} for c, m in options]}
    resp = s.post(BASE + "/admin/tests/%s/questions" % tid, json=body)
    if resp.status_code != 200:
        raise RuntimeError("题目创建失败 %s: %s" % (content, resp.text))


# ══════════ 1. 修复主题2 + 补足到4题 ══════════
def fix_theme2():
    detail = s.get(BASE + "/admin/tests/2").json()
    titles = [t["title"] for t in existing_tests()]
    if detail.get("title") not in titles:
        log("[!] 主题2不存在，跳过修复")
        return
    roles = s.get(BASE + "/admin/roles?test_id=2").json()
    codes = [r["code"] for r in roles]
    if not codes:
        log("[!] 主题2没有角色，跳过补题（请先在后台建角色）")
        return
    codes.sort()
    p1, p2 = codes[0], codes[-1]
    qs = detail["questions"]
    log("[*] 主题2当前: %d 题, 角色代号: %s" % (len(qs), " ".join(codes)))

    for q in qs:
        if len(q["options"]) == 0:
            s.put(BASE + "/admin/questions/%s" % q["id"], json={
                "content": q["content"], "sort_order": q["sort_order"],
                "options": [
                    {"content": "更欣赏「%s」这样的人" % roles[0]["name"], "score_map": {p1: 2, p2: 1}},
                    {"content": "更欣赏「%s」这样的人" % roles[-1]["name"], "score_map": {p2: 2, p1: 1}},
                    {"content": "两人都想深交", "score_map": {p1: 1, p2: 1}},
                    {"content": "先看看再说", "score_map": {p1: 1, p2: 1}},
                ]})
            log("[fix] 主题2坏题「%s」(0选项) 已补上4个选项" % q["content"])

    need = 4 - len(detail["questions"])
    for i in range(need):
        add_question(2, "补充分题 %d" % (len(qs) + i + 1), [
            ("选择「%s」" % roles[0]["name"], {p1: 2, p2: 1}),
            ("选择「%s」" % roles[-1]["name"], {p2: 2, p1: 1}),
            ("都想要", {p1: 1, p2: 1}),
            ("都不选，我再想想", {p1: 1, p2: 1}),
        ], 0)
        log("[+] 主题2 补1题 → %d 题" % (len(qs) + i + 1))


